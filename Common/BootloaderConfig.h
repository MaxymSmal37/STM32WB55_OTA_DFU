#ifndef BOOTLOADERCONFIG_H
#define BOOTLOADERCONFIG_H


#define BOOTLOADER_SIZE   0x10000U

#define APP_FLASH_START   (FLASH_BASE + BOOTLOADER_SIZE)   /* 0x08010000 */
#define APP_FLASH_SIZE   (480U * 1024U)
#define APP_FLASH_END    (APP_FLASH_START + APP_FLASH_SIZE)
 
#define FLASH_WRITE_CHUNK 8U

#define FLASH_BUSY_MASK  (FLASH_SR_BSY | FLASH_SR_CFGBSY)
#define FLASH_ERR_MASK   (FLASH_SR_PROGERR | FLASH_SR_WRPERR | FLASH_SR_PGAERR | \
                          FLASH_SR_SIZERR  | FLASH_SR_PGSERR | FLASH_SR_MISERR | \
                          FLASH_SR_FASTERR | FLASH_SR_OPTVERR)
#define APP_FLASH_PAGES  (APP_FLASH_SIZE / FLASH_PAGE_SIZE)

#define APP_ERASE_FLASH_TIMEOUT_MS 1000U
#define APP_WRITE_FLASH_TIMEOUT_MS 1000U

#endif /* BOOTLOADERCONFIG_H */