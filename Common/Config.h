#ifndef CONFIG_H
#define CONFIG_H

#define FW_VERSION_PREFIX_MAJOR "A"
#define FW_VERSION_PREFIX_MINOR "X"

#define FW_VERSION_MAJOR         0
#define FW_VERSION_MINOR         0
#define FW_VERSION_PATCH         1

#define STRINGIFY_IMPL(x) #x
#define STRINGIFY(x)      STRINGIFY_IMPL(x)

#define FW_VERSION_STRING \
    FW_VERSION_PREFIX_MAJOR \
    FW_VERSION_PREFIX_MINOR "." \
    STRINGIFY(FW_VERSION_MAJOR) "." \
    STRINGIFY(FW_VERSION_MINOR) "." \
    STRINGIFY(FW_VERSION_PATCH)

#endif /* CONFIG_H */
